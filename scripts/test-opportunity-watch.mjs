import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ entryPoints: ['base44/functions/checkOpportunityWatches/core.ts'], bundle: true, format: 'esm', platform: 'node', write: false, logLevel: 'silent' });
const { compareWatchResults } = await import('data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64'));
const stamp = '2026-10-04T12:00:00.000Z';
const a = { id: '123', title: 'Ayuda', status: 'open', closesAt: '2026-12-31', sourceUrl: 'https://www.infosubvenciones.es/123' };
const baseline = compareWatchResults({ id: 'watch-1' }, [a], stamp);
assert.equal(baseline.detected, 0);
assert.equal(baseline.unread_count, 0);
const repeat = compareWatchResults(baseline, [a], stamp);
assert.equal(repeat.detected, 0);
const changed = compareWatchResults(repeat, [{ ...a, closesAt: '2027-01-15' }], stamp);
assert.equal(changed.detected, 1);
assert.equal(changed.unread_count, 1);
assert.equal(changed.unread_items[0].url, a.sourceUrl);
const repeated = compareWatchResults(changed, [{ ...a, closesAt: '2027-01-15' }], stamp);
assert.equal(repeated.detected, 0);
assert.equal(repeated.unread_count, 1);
const fresh = compareWatchResults(repeated, [{ id: '999', title: 'Licitación', kind: 'abierta', url: 'https://contrataciondelestado.es/999' }], stamp);
assert.equal(fresh.detected, 1);
assert.equal(fresh.unread_count, 2);
console.log('Radar: referencia inicial, cambios, avisos e idempotencia OK');

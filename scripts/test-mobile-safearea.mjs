import assert from 'node:assert/strict';
import fs from 'node:fs';
import postcss from 'postcss';
import {collisionInsets} from '../src/lib/safeArea.mjs';
import {markNotificationReads} from '../src/lib/notificationRead.mjs';
const html=fs.readFileSync('index.html','utf8'),css=fs.readFileSync('src/index.css','utf8');
const viewports=[...html.matchAll(/<meta\s+name="viewport"\s+content="([^"]+)"/g)];
assert.equal(viewports.length,1);assert.match(viewports[0][1],/viewport-fit=cover/);
assert.ok(!/user-scalable=no|maximum-scale\s*=\s*1/.test(viewports[0][1]),'Do not disable accessibility zoom');
assert.deepEqual(collisionInsets(),{top:12,right:12,bottom:12,left:12});
assert.deepEqual(collisionInsets({top:'59px',right:'0px',bottom:'34px',left:'47px'}),{top:59,right:12,bottom:34,left:47});
assert.deepEqual(collisionInsets({top:'garbage',left:'-5px'}),{top:12,right:12,bottom:12,left:12});
const parsed=postcss.parse(css);let shellTop=false;
parsed.walkRules(rule=>{if(rule.selector==='.taxea-future-shell')rule.walkDecls('padding-top',decl=>{shellTop=decl.value==='var(--taxea-safe-top)';});});
assert.ok(shellTop);
const layout=fs.readFileSync('src/components/layout/AppLayout.jsx','utf8'),topbar=fs.readFileSync('src/components/layout/TopBar.jsx','utf8');
assert.ok(!/taxea-future-shell[^\n]+safe-area-padded/.test(layout));
assert.ok(!/taxea-future-topbar[^\n]+safe-area-pt/.test(topbar));
assert.match(css,/\.taxea-dialog-content[^}]+max-height:calc\(100dvh/);
assert.match(css,/prefers-reduced-motion/);
assert.match(css,/\.taxea-future-bottomnav[^}]+--taxea-safe-bottom/);
assert.match(css,/\.taxea-mobile-screen:not\(\[hidden\]\)/);
for(const file of ['select.jsx','dropdown-menu.jsx'])assert.match(fs.readFileSync('src/components/ui/'+file,'utf8'),/collisionPadding=\{safePadding\}/);
let ui=[{id:'a',leida:false},{id:'b',leida:false},{id:'c',leida:true},{id:'untouched',leida:false}],resolveA,started=[],rolled=[];
const gate=new Promise(resolve=>{resolveA=resolve;});
const apply=(ids,leida)=>{ui=ui.map(row=>ids.includes(row.id)?{...row,leida}:row);};
const operation=markNotificationReads({rows:ui,ids:['a','a','b','c','missing'],optimistic:ids=>apply(ids,true),rollback:ids=>{rolled=ids;apply(ids,false);},persist:async id=>{started.push(id);if(id==='b')throw new Error('offline');await gate;}});
assert.equal(ui.find(row=>row.id==='a').leida,true,'Feedback is immediate, before persistence settles');
assert.equal(ui.find(row=>row.id==='untouched').leida,false);
resolveA();const result=await operation;
assert.deepEqual(started.sort(),['a','b']);assert.deepEqual(result.updated,['a']);assert.deepEqual(result.failed,['b']);assert.deepEqual(rolled,['b']);
assert.equal(ui.find(row=>row.id==='a').leida,true);assert.equal(ui.find(row=>row.id==='b').leida,false);
let active=0,max=0,persisted=0;
const many=Array.from({length:19},(_,i)=>({id:String(i),leida:false}));
const complete=await markNotificationReads({rows:many,ids:many.map(r=>r.id),optimistic(){},rollback(){throw new Error('Unexpected rollback');},persist:async()=>{persisted++;active++;max=Math.max(max,active);await Promise.resolve();active--;}});
assert.equal(complete.updated.length,19);assert.equal(persisted,19);assert.ok(max<=4,'Batch concurrency is bounded');
const empty=await markNotificationReads({rows:[],ids:['outside'],persist(){throw new Error('Foreign row cannot be persisted');},optimistic(){throw new Error('Empty operation');},rollback(){}});
assert.deepEqual(empty,{updated:[],failed:[]});
console.log('Viewport + CSS single-inset ownership + portrait/landscape collision arithmetic + safe menu contracts + immediate notification read/partial rollback/deduplication/bounded batches pass. No external calls; nonzero physical device insets still require iPhone QA.');

